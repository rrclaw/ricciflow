/* 生成 sprite 元素。cls 里带 s2/s4/s5/s6 改像素大小 */
function makeAvatar(key, cls){
  const sp = SPRITES[key] || SPRITES.guest;
  const unit = !cls ? 3 : cls.includes('s2') ? 2 : cls.includes('s4') ? 4 : cls.includes('s5') ? 5 : cls.includes('s6') ? 6 : 3;
  const w = sp.rows[0].length, h = sp.rows.length;
  const node = document.createElement('div');
  node.className = 'px-avatar' + (cls ? ' ' + cls : '');
  node.style.width = w*unit + 'px';
  node.style.height = h*unit + 'px';
  const b = document.createElement('b');
  const shadows = [];
  sp.rows.forEach((row, y)=>{
    for(let x=0; x<row.length; x++){
      const c = row[x];
      if(!c || c === '.' || c === ' ') continue;
      const color = sp.pal[c];
      if(!color) continue;
      shadows.push(`${x*unit}px ${y*unit}px 0 ${color}`);
    }
  });
  b.style.boxShadow = shadows.join(',');
  node.appendChild(b);
  return node;
}
function avatarHTML(key, cls){ return makeAvatar(key, cls).outerHTML; }


/* ==========================================================================
   canvas 栅格化：把字符网格 sprite 画到 canvas 上（世界层用）
   ========================================================================== */
function drawSpriteOn(ctx, key, x, y, px){
  const sp = SPRITES[key]; if(!sp) return;
  sp.rows.forEach((row, ry)=>{
    for(let rx=0; rx<row.length; rx++){
      const c = row[rx];
      if(!c || c==='.' || c===' ') continue;
      const col = sp.pal[c]; if(!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x + rx*px, y + ry*px, px, px);
    }
  });
}

